def is_admin():
    """Check if the current process has admin privileges"""
    try:
        return bool(ctypes.windll.shell32.IsUserAnAdmin())
    except (AttributeError, OSError):
        return False


def run_as_admin():
    """Relaunch this program elevated. Returns True if the UAC prompt was accepted."""
    args = sys.argv[1:] if getattr(sys, "frozen", False) else [os.path.abspath(__file__), *sys.argv[1:]]
    # ShellExecuteW returns a value > 32 on success; declining UAC returns 5
    return ctypes.windll.shell32.ShellExecuteW(
        None, "runas", sys.executable, subprocess.list2cmdline(args), None, 1) > 32


def find_choco():
    """Path to choco.exe, or None. Checks the install dir too, since PATH isn't refreshed after a fresh install."""
    candidates = [shutil.which("choco")]
    for root in (os.environ.get("ChocolateyInstall"),
                 os.path.join(os.environ.get("ProgramData", r"C:\ProgramData"), "chocolatey")):
        if root:
            candidates.append(os.path.join(root, "bin", "choco.exe"))
    return next((path for path in candidates if path and os.path.isfile(path)), None)


def run_hidden(cmd):
    """Run a console program without flashing a console window."""
    return subprocess.run(cmd, stdin=subprocess.DEVNULL, capture_output=True, text=True, errors="replace",
                          creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0))


def choco_install(choco, package):
    """Install one package and return choco's exit code."""
    # The id becomes a command-line argument: reject anything that could be read as an option
    if not isinstance(package, str) or not PACKAGE_ID.fullmatch(package):
        raise ValueError(f"invalid package id: {package!r}")
    return run_hidden([choco, "install", package, "-y", "--no-progress"]).returncode


def validate_catalog(catalog):
    """Return catalog if it is {category: {app name: {"package": id, ...}}}, else raise ValueError."""
    if not isinstance(catalog, dict) or not catalog:
        raise ValueError("catalog is empty")
    for category, apps in catalog.items():
        if not isinstance(apps, dict):
            raise ValueError(f"{category}: expected a list of apps")
        for name, app in apps.items():
            if not (isinstance(app, dict)
                    and isinstance(app.get("package"), str) and PACKAGE_ID.fullmatch(app["package"])
                    and isinstance(app.get("description", ""), str)
                    and isinstance(app.get("icon", ""), str)
                    and isinstance(app.get("size", 0), (int, float))):
                raise ValueError(f"{category}/{name}: invalid entry")
    return catalog


def load_catalog():
    """The latest app list from the repo this build came from, or the copy bundled with the app."""
    if REPO:
        url = f"https://raw.githubusercontent.com/{REPO}/{BRANCH}/{CATALOG_PATH}"
        try:
            with urllib.request.urlopen(url, timeout=10) as response:
                return validate_catalog(json.load(response))
        except Exception:
            pass  # offline, repo moved or bad data: use the bundled copy
    with open(os.path.join(APP_DIR, "packages.json"), encoding="utf-8") as f:
        return validate_catalog(json.load(f))


