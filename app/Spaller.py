class CatalogLoader(QThread):
    loaded = Signal(object)
    failed = Signal(str)

    def run(self):
        try:
            self.loaded.emit(load_catalog())
        except Exception as e:
            self.failed.emit(str(e))


class ChocolateySetupThread(QThread):
    """Runs the official Chocolatey installer; read `message` after `finished`."""
    message = ""

    def run(self):
        try:
            result = run_hidden(["powershell", "-NoProfile", "-ExecutionPolicy", "Bypass",
                                 "-Command", CHOCO_INSTALL_SCRIPT])
            output = (result.stderr or result.stdout).strip()
            self.message = output.splitlines()[-1] if output else f"exit code {result.returncode}"
        except OSError as e:
            self.message = str(e)


class InstallationThread(QThread):
    """Installs apps one by one; read the result attributes after `finished`."""
    progress_updated = Signal(int, int, str)  # apps done, total, current app

    def __init__(self, choco, apps):
        super().__init__()
        self.choco = choco
        self.apps = apps  # [(app_id, name, package)]
        self.installed = []  # app ids
        self.failed = []  # human-readable reasons
        self.reboot_required = False
        self.cancelled = False

    def run(self):
        for i, (app_id, name, package) in enumerate(self.apps):
            if self.isInterruptionRequested():
                self.cancelled = True
                break
            self.progress_updated.emit(i, len(self.apps), name)
            try:
                code = choco_install(self.choco, package)
            except (OSError, ValueError) as e:
                self.failed.append(f"{name}: {e}")
                continue
            if code in CHOCO_SUCCESS_CODES:
                self.installed.append(app_id)
                self.reboot_required |= code != 0
            else:
                self.failed.append(f"{name} (exit code {code})")


